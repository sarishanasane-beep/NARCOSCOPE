@dataclass
class SeedSummary:
    documents: int = 0
    duplicates: int = 0
    people: int = 0
    organizations: int = 0
    locations: int = 0
    events: int = 0
    cases: int = 0
    relationships: int = 0
    facts: int = 0
    claims: int = 0
    pending_candidates: int = 0
    confirmed_candidates: int = 0


def _confirm_case_matches(db: Session) -> None:
    # Only reviewable candidates may be confirmed. Candidates already in a
    # terminal state (e.g. CONFIRMED by a previous seed run) are skipped —
    # confirm_candidate() correctly rejects them with CandidateStateError.
    for candidate in (
        db.query(Candidate)
        .filter(
            Candidate.candidate_type == CANDIDATE_TYPE_CASE_MATCH,
            Candidate.status.in_([CANDIDATE_STATUS_PENDING, CANDIDATE_STATUS_EDITED]),
        )
        .all()
    ):
        confirm_candidate(db, candidate, reviewed_by="demo-seed", reason="DEMO DATA — confirmed by seed")


def _set_location_parents(db: Session) -> None:
    """Link locations into a hierarchy (Pune -> Maharashtra -> India)."""
    for child_name, parent_name in DEMO_LOCATION_PARENTS.items():
        child = (
            db.query(Location)
            .join(Entity, Entity.entity_id == Location.entity_id)
            .filter(Entity.canonical_name == child_name)
            .first()
        )
        parent = (
            db.query(Location)
            .join(Entity, Entity.entity_id == Location.entity_id)
            .filter(Entity.canonical_name == parent_name)
            .first()
        )
        if child and parent:
            child.parent_location_id = parent.location_id


def _add_derived_candidate(db: Session) -> None:
    """One derived relationship, left PENDING for review.

    Arjun Mehta LOCATED_IN Mumbai is DERIVED from two confirmed facts:
      Arjun Mehta ARRESTED_IN Operation Bluewater
      Operation Bluewater OCCURRED_IN Mumbai
    Derivation requires human confirmation — it is never auto-confirmed.
    """
    # Idempotency guard: re-running the seed against a previously seeded
    # database must not stack duplicate derived candidates for review.
    for existing in (
        db.query(Candidate)
        .filter(
            Candidate.candidate_type == CANDIDATE_TYPE_RELATIONSHIP,
            Candidate.status == CANDIDATE_STATUS_PENDING,
        )
        .all()
    ):
        pd = existing.proposed_data or {}
        if (
            pd.get("source_name") == "Arjun Mehta"
            and pd.get("relationship_type") == "LOCATED_IN"
            and pd.get("target_name") == "Mumbai"
        ):
            return

    evidence = (
        db.query(Evidence)
        .filter(Evidence.exact_text.ilike("%Arjun Mehta was arrested during Operation Bluewater%"))
        .first()
    )
    document = db.query(Document).filter(Document.filename == DEMO_DOCUMENTS[0].filename).first()
    db.add(
        Candidate(
            candidate_id=str(uuid.uuid4()),
            candidate_type=CANDIDATE_TYPE_RELATIONSHIP,
            proposed_data={
                "source_name": "Arjun Mehta",
                "source_type": "PERSON",
                "relationship_type": "LOCATED_IN",
                "target_name": "Mumbai",
                "target_type": "LOCATION",
                "classification": "DERIVED",
            },
            source_document_id=document.document_id if document else None,
            evidence_id=evidence.evidence_id if evidence else None,
            confidence=0.5,
            reason=(
                "Derived from confirmed facts: Arjun Mehta ARRESTED_IN Operation Bluewater "
                "and Operation Bluewater OCCURRED_IN Mumbai. Requires human review."
            ),
            status="PENDING",
        )
    )


def seed_demo(db: Session | None = None) -> SeedSummary:
    own_session = db is None
    db = db or SessionLocal()
    summary = SeedSummary()
    try:
        # --- 1. Upload + process every demo document through the real pipeline ---
        for demo_doc in DEMO_DOCUMENTS:
            # Idempotency: never re-upload a demo document that is already
            # present in the database (stable demo filename). This makes a
            # re-seed a true no-op even if regenerated PDF/DOCX bytes are
            # not byte-identical across runs (PyMuPDF embeds time-dependent
            # metadata that defeats SHA-256 exact-duplicate detection, which
            # would re-process the file and create duplicate trusted
            # records). The explicit duplicate upload below still exercises
            # the SHA-256 duplicate feature on every run.
            already_seeded = (
                db.query(Document)
                .filter(Document.filename == demo_doc.filename)
                .first()
            )
            if already_seeded is not None:
                summary.documents += 1
                continue
            data = _generate_file(demo_doc)
            result = receive_upload_bytes(
                db,
                filename=demo_doc.filename,
                data=data,
                metadata={
                    "publisher": demo_doc.publisher,
                    "agency": demo_doc.agency,
                    "source_type": demo_doc.source_type,
                    "publication_date": demo_doc.publication_date,
                },
            )
            db.commit()
            summary.documents += 1

        # --- 2. Exact duplicate (same bytes as the first document) ---
        first = DEMO_DOCUMENTS[0]
        duplicate_result = receive_upload_bytes(
            db,
            filename=DUPLICATE_FILENAME,
            data=_generate_file(first),
            metadata={
                "publisher": first.publisher,
                "agency": first.agency,
                "source_type": first.source_type,
                "publication_date": first.publication_date,
            },
        )
        db.commit()
        if duplicate_result.duplicate_of:
            summary.duplicates += 1

        # --- 3. Confirm curated candidates (trusted data) ---
        entity_candidates = (
            db.query(Candidate)
            .filter(
                Candidate.candidate_type.in_([CANDIDATE_TYPE_ENTITY, CANDIDATE_TYPE_LOCATION]),
                Candidate.status.in_([CANDIDATE_STATUS_PENDING, CANDIDATE_STATUS_EDITED]),
            )
            .order_by(Candidate.created_at.asc())
            .all()
        )
        for candidate in entity_candidates:
            name = (candidate.proposed_data or {}).get("name")
            entity_type = (candidate.proposed_data or {}).get("entity_type")
            if entity_type == "LOCATION" and name in LOCATIONS_CONFIRM:
                confirm_candidate(db, candidate, reviewed_by="demo-seed", reason="DEMO DATA — confirmed by seed")
                summary.confirmed_candidates += 1
            elif entity_type == "ORGANIZATION" and name in ORGANIZATIONS_CONFIRM:
                confirm_candidate(db, candidate, reviewed_by="demo-seed", reason="DEMO DATA — confirmed by seed")
                summary.confirmed_candidates += 1
            elif entity_type == "OTHER" and name in OPERATIONS_CONFIRM:
                confirm_candidate(db, candidate, reviewed_by="demo-seed", reason="DEMO DATA — confirmed by seed")
                summary.confirmed_candidates += 1
            elif entity_type == "PERSON" and name in PEOPLE_CONFIRM:
                confirm_candidate(db, candidate, reviewed_by="demo-seed", reason="DEMO DATA — confirmed by seed")
                summary.confirmed_candidates += 1

        db.commit()

        _confirm_case_matches(db)
        db.commit()

        for candidate in (
            db.query(Candidate)
            .filter(
                Candidate.candidate_type.in_([CANDIDATE_TYPE_EVENT, CANDIDATE_TYPE_RELATIONSHIP, CANDIDATE_TYPE_FACT]),
                Candidate.confidence >= 0.6,
                Candidate.status.in_([CANDIDATE_STATUS_PENDING, CANDIDATE_STATUS_EDITED]),
            )
            .order_by(Candidate.created_at.asc())
            .all()
        ):
            # POSSIBLE_MATCH candidates ALWAYS require human confirmation —
            # the seed must never auto-confirm an identity match.
            if (candidate.proposed_data or {}).get("relationship_type") == "POSSIBLE_MATCH":
                continue
            confirm_candidate(db, candidate, reviewed_by="demo-seed", reason="DEMO DATA — confirmed by seed")
            summary.confirmed_candidates += 1
        db.commit()

        # --- 4. Location hierarchy ---
        _set_location_parents(db)
        db.commit()

        # --- 5. Derived relationship (PENDING — waiting for review) ---
        _add_derived_candidate(db)
        db.commit()

        # --- 6. Counts ---
        summary.people = db.query(Person).count()
        summary.organizations = db.query(Organization).count()
        summary.locations = db.query(Location).count()
        summary.events = db.query(Event).count()
        summary.cases = db.query(Case).count()
        summary.relationships = db.query(Relationship).count()
        summary.facts = db.query(Fact).count()
        summary.claims = db.query(Claim).count()
        summary.pending_candidates = db.query(Candidate).filter(Candidate.status == "PENDING").count()

        log_event(
            logger, "demo_seed_complete",
            documents=summary.documents, duplicates=summary.duplicates, people=summary.people,
            organizations=summary.organizations, locations=summary.locations, events=summary.events,
            cases=summary.cases, relationships=summary.relationships, facts=summary.facts,
            claims=summary.claims, pending_candidates=summary.pending_candidates,
        )
        return summary
    finally:
        if own_session:
            db.close()


