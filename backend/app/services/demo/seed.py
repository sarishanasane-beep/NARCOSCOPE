# ---------------------------------------------------------------------------
# File generation
# ---------------------------------------------------------------------------

def _build_txt_bytes(content: str) -> bytes:
    return content.encode("utf-8")


def _build_docx_bytes(content: str) -> bytes:
    from docx import Document as DocxDocument

    buffer = io.BytesIO()
    doc = DocxDocument()
    for line in content.splitlines():
        doc.add_paragraph(line)
    # Pin core properties so regenerated bytes are identical across runs.
    # A time-dependent docProps/core.xml would hash differently on re-seed
    # and defeat SHA-256 exact-duplicate detection, causing the document to
    # be re-processed and duplicate trusted records to be created.
    fixed = datetime(2026, 1, 1, 0, 0, 0)
    doc.core_properties.created = fixed
    doc.core_properties.modified = fixed
    doc.save(buffer)
    return buffer.getvalue()


def _build_pdf_bytes(content: str) -> bytes:
    import fitz

    pdf = fitz.open()
    page = pdf.new_page()
    y = 60
    for line in content.splitlines():
        if not line.strip():
            y += 14
            continue
        page.insert_text((60, y), line, fontsize=10)
        y += 14
    # Pin timestamps so regenerated bytes are identical across runs.
    # Without this, PyMuPDF stamps the current time into the PDF metadata
    # (CreationDate/ModDate), so the re-seeded file hashes differently and
    # is NOT detected as an exact duplicate — it gets re-processed, and the
    # seed then confirms fresh candidates into duplicate trusted records.
    pdf.set_metadata(
        {
            "title": "NARCOSCOPE Demo Data",
            "author": "NARCOSCOPE Demo Unit",
            "creationDate": "D:20260101000000Z",
            "modDate": "D:20260101000000Z",
        }
    )
    data = pdf.tobytes()
    pdf.close()
    return data


def _generate_file(demo_doc) -> bytes:
    if demo_doc.format == "docx":
        return _build_docx_bytes(demo_doc.content)
    if demo_doc.format == "pdf":
        return _build_pdf_bytes(demo_doc.content)
    return _build_txt_bytes(demo_doc.content)


